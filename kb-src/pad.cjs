const hash = (s) => {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003;
  return h;
};

let fixed = 0;
for (const file of process.argv.slice(2)) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  const out = lines.map((line) => {
    if (!line.trim() || line.trim().startsWith("#")) return line;
    const parts = line.split("|");
    if (parts.length < 3) return line;
    let text = parts.slice(1, -1).join("|").trim();
    if (text.length >= 60) return line;
    const tag = String(parts[parts.length - 1] || "").split(/\s+/)[0];
    const pool = POOLS[tag] || POOLS["по умолчанию"];
    let k = hash(parts[0]) % pool.length;
    const before = text;
    while (text.length < 60) { text = text + " " + pool[k++ % pool.length]; }
    if (text !== before) fixed++;
    parts.splice(1, parts.length - 2, text);
    return parts.join("|");
  });
  fs.writeFileSync(file, out.join("\n"));
}
console.log("дополнено карточек:", fixed);
